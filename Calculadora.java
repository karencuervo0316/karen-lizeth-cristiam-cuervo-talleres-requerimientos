package com.example;

public class Calculadora {

    public double suma(double a, double b){
        return a + b;
    } 

    public double resta(double a, double b){
        return a - b;
    } 

    public double multipliacion(double a, double b){
        return a * b;
    } 

    public double divsion(double a, double b){
        return a / b;
    } 

}
